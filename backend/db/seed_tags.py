def _find_or_create(cur, name, type_name, parent_id, description):
    if parent_id is None:
        cur.execute(
            "SELECT id FROM tags WHERE kind='tag' AND name = ? AND type_name = ? AND parent_id IS NULL",
            (name, type_name),
        )
    else:
        cur.execute(
            "SELECT id FROM tags WHERE kind='tag' AND name = ? AND type_name = ? AND parent_id = ?",
            (name, type_name, parent_id),
        )
    row = cur.fetchone()
    if row:
        return row[0]
    cur.execute(
        "INSERT INTO tags (name, kind, type_name, parent_id, description) VALUES (?, 'tag', ?, ?, ?)",
        (name, type_name, parent_id, description),
    )
    return cur.lastrowid


def main():
    conn = sqlite3.connect(DB_PATH)
    conn.execute("PRAGMA foreign_keys=ON")
    cur = conn.cursor()

    created = 0
    skipped = 0
    for type_name, first, second, description in ALL_TAGS:
        # 确保标签类型存在
        cur.execute("SELECT id FROM tags WHERE kind='type' AND name = ?", (type_name,))
        if not cur.fetchone():
            cur.execute(
                "INSERT INTO tags (name, kind, sort_order) VALUES (?, 'type', (SELECT COALESCE(MAX(sort_order),0)+1 FROM tags WHERE kind='type'))",
                (type_name,),
            )

        # 一级标签
        cur.execute(
            "SELECT id FROM tags WHERE kind='tag' AND name = ? AND type_name = ? AND parent_id IS NULL",
            (first, type_name),
        )
        row = cur.fetchone()
        if row:
            first_id = row[0]
            skipped += 1
        else:
            cur.execute(
                "INSERT INTO tags (name, kind, type_name, parent_id, description) VALUES (?, 'tag', ?, NULL, ?)",
                (first, type_name, description),
            )
            first_id = cur.lastrowid
            created += 1

        # 二级标签
        if second:
            cur.execute(
                "SELECT id FROM tags WHERE kind='tag' AND name = ? AND type_name = ? AND parent_id = ?",
                (second, type_name, first_id),
            )
            if not cur.fetchone():
                cur.execute(
                    "INSERT INTO tags (name, kind, type_name, parent_id, description) VALUES (?, 'tag', ?, ?, ?)",
                    (second, type_name, first_id, description if not row else None),
                )
                created += 1
            else:
                skipped += 1

    conn.commit()
    print(f"标签初始化完成：新增 {created} 个，已存在跳过 {skipped} 个")
    conn.close()


